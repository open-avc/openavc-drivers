"""KNX Association worked examples and normative datapoint boundary values.

Sources: KNX IP Secure v01.01.02 Annex A.3 (pp.58–60); Project Schema23
v01.00.00 password example; Datapoint Types v02.02.01 §§3.6,3.18,3.19.
No expected cipher value is generated by this test or by the simulator.
"""
import io

from _platform_probe import load_driver

DRV = load_driver("utility/knx_ip.py")
SIM = load_driver("utility/knx_ip_sim.py")


def test_project_password_matches_the_published_a_example():
    """Schema23: password a derives this Base64 AES ZIP password."""
    inner = io.BytesIO()
    with DRV.pyzipper.AESZipFile(inner, "w", encryption=DRV.pyzipper.WZ_AES) as archive:
        archive.setpassword(b"+FAwP4iI7/Pu4WB3HdIHbbFmteLahPAVkjJShKeozAA=")
        archive.writestr("0.xml", b"<Project/>")
    outer = io.BytesIO()
    with DRV.pyzipper.AESZipFile(outer, "w") as archive:
        archive.writestr("P-1234.zip", inner.getvalue())
    project = DRV.ProjectArchive(outer.getvalue(), "a")
    try:
        assert project.project() == b"<Project/>"
    finally:
        project.archive.close()


def test_switch_shade_and_percentage_wire_boundaries():
    """DPT 1.001,1.008: off/up=0, on/down=1; DPT 5.001: 0%=0,100%=255."""
    assert DRV.encode_value({"property": "on"}, False).value == 0
    assert DRV.encode_value({"property": "on"}, True).value == 1
    assert DRV.encode_value({"property": "move"}, "up").value == 0
    assert DRV.encode_value({"property": "move"}, "down").value == 1
    assert DRV.encode_value({"property": "level"}, 0).value == (0,)
    assert DRV.encode_value({"property": "level"}, 100).value == (255,)


def test_scene_numbers_are_one_based_and_never_set_the_learn_bit():
    """DPT 17.001/18.001: display 1–64, wire 0–63; scene-control bit7=0 recalls."""
    assert DRV.encode_value({"property": "recall", "scene": 1}, None).value == (0,)
    assert DRV.encode_value({"property": "recall", "scene": 64}, None).value == (63,)


def test_secure_password_hashes_match_annex_a():
    """IP Secure Annex A.2/A.3: trustme device auth and secret user password."""
    assert SIM.password_key("trustme", "device-authentication-code").hex() == "e158e4012047bd6cc41aafbc5c04c1fc"
    assert SIM.password_key("secret", "user-password").hex() == "03fcedb66660251ec81a1a716901696a"


def test_secure_wrapper_matches_the_published_ciphertext_and_mac():
    """IP Secure Annex A.3.3: the complete known AES-CBC-MAC/CTR calculation."""
    key = bytes.fromhex("289426c2912535ba98279a4d1843c487")
    nonce = bytes.fromhex("00000000000000fa12345678affe")
    header = bytes.fromhex("06100950003e0001")
    plain = bytes.fromhex("06100953001800011f1d59ea9f12a152e5d9727f08462cde")
    mac = SIM.cbc_mac(key, header, plain, nonce + b"\0\x18")
    assert mac.hex() == "602280d0896beaa7106e7248f67f2eef"
    encrypted = SIM.crypt(key, nonce + b"\xff\0", mac + plain)
    assert encrypted[:16].hex() == "52dba8e7e4bd80bd7d868a3ae78749de"
    assert encrypted[16:].hex() == "7915a4f36e6e4208d28b4a207d8f35c0d138c26a7b5e7169"
    published = header + nonce + bytes.fromhex(
        "7915a4f36e6e4208d28b4a207d8f35c0d138c26a7b5e7169"
        "52dba8e7e4bd80bd7d868a3ae78749de"
    )
    peer = SIM.Session("trustme", "secret", 1)
    peer.key = key
    assert peer.unwrap(published) == plain


def test_data_secure_cipher_matches_application_layer_annex_c():
    """Application Layer v02.01.01 C.1.1, pp187–188: independent known cipher."""
    key = bytes(range(16))
    plain = bytes.fromhex("03d705351001202122232425262728292a2b2c2d2e2f")
    nonce = bytes.fromhex("000000000004ff67ff00")
    first = nonce + bytes.fromhex("000003f10016")
    mac = SIM.cbc_mac(key, b"\x90", plain, first)[:4]
    assert mac.hex() == "056a57e9"
    encrypted = SIM.crypt(key, nonce + bytes.fromhex("000000000100"), mac + plain)
    assert encrypted[:4].hex() == "0d8fc168"
    assert encrypted[4:].hex() == "6767242a2308ca76a11774214ee4cf5d94909f743d05"
